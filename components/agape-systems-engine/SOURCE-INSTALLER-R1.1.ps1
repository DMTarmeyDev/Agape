function Say([string]$Name,[string]$Value,[string]$Color='Cyan') {
    Write-Host ("{0}={1}" -f $Name,$Value) -ForegroundColor $Color
}

function Find-Core {
    $candidates = @(
        (Join-Path $env:LOCALAPPDATA 'DMT-Core-V3.1\SecondBrain\dmt-second-brain'),
        (Join-Path $env:LOCALAPPDATA 'DMT-Core-V3.1-Early-Alpha\SecondBrain\dmt-second-brain'),
        (Join-Path $env:LOCALAPPDATA 'DMT-Core-V1.7\SecondBrain\dmt-second-brain')
    )
    foreach($c in $candidates) {
        if((Test-Path -LiteralPath $c -PathType Container) -and (Test-Path -LiteralPath (Join-Path $c 'app.py') -PathType Leaf)) {
            return [IO.Path]::GetFullPath($c)
        }
    }
    throw 'AGAPE_CORE_NOT_FOUND'
}

function Find-Python {
    $p = Get-Command python.exe -ErrorAction SilentlyContinue
    if(-not $p) { $p = Get-Command python -ErrorAction SilentlyContinue }
    if(-not $p) { throw 'PYTHON_NOT_FOUND' }
    return $p.Source
}

function Test-Port([int]$Port) {
    try {
        $c = New-Object Net.Sockets.TcpClient
        $a = $c.BeginConnect('127.0.0.1',$Port,$null,$null)
        $ok = $a.AsyncWaitHandle.WaitOne(350,$false)
        if($ok) { $c.EndConnect($a) }
        $c.Close()
        return [bool]$ok
    } catch { return $false }
}

function Wait-Health([int]$Port,[int]$Seconds=20) {
    $deadline = (Get-Date).AddSeconds($Seconds)
    while((Get-Date) -lt $deadline) {
        try {
            $h = Invoke-RestMethod -Uri ("http://127.0.0.1:{0}/api/health" -f $Port) -TimeoutSec 2
            if($h.ok) { return $h }
        } catch {}
        Start-Sleep -Milliseconds 300
    }
    return $null
}

function Stop-EngineOnPort([int]$Port) {
    try {
        $conn = Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue | Select-Object -First 1
        if($conn) {
            $proc = Get-CimInstance Win32_Process -Filter ("ProcessId=" + [int]$conn.OwningProcess) -ErrorAction SilentlyContinue
            if($proc -and ([string]$proc.CommandLine -match 'agape-systems-engine|engine_entry\.py|agape_systems_engine')) {
                Stop-Process -Id ([int]$conn.OwningProcess) -Force -ErrorAction Stop
                Start-Sleep -Milliseconds 600
                Say 'OLD_WORK_ENGINE_STOP' 'PASS' 'Green'
            } else {
                throw ("PORT_{0}_IN_USE_BY_OTHER_PROCESS_PID={1}" -f $Port,$conn.OwningProcess)
            }
        }
    } catch { throw }
}

function Start-EngineProcess([string]$Python,[string]$Entry,[int]$Port,[string]$Data,[string]$Core,[string]$Out,[string]$Err) {
    $args = ('"{0}" --port {1} --data-root "{2}" --core-root "{3}" --no-browser' -f $Entry,$Port,$Data,$Core)
    return Start-Process -FilePath $Python -ArgumentList $args -WindowStyle Hidden -PassThru -RedirectStandardOutput $Out -RedirectStandardError $Err
}

