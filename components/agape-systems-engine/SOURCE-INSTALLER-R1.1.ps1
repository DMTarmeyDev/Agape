            if(-not $task) { throw 'SCHEDULED_TASK_VERIFY_FAILED' }
            $Autostart = 'PASS'
            $AutostartMethod = 'TASK_SCHEDULER'
            Say 'AUTOSTART_TASK' 'PASS_VERIFIED' 'Green'
        } catch {
            Say 'AUTOSTART_TASK' ('WARN ' + $_.Exception.Message) 'Yellow'
            $StartupDir = [Environment]::GetFolderPath('Startup')
            if([string]::IsNullOrWhiteSpace($StartupDir)) { throw 'STARTUP_FOLDER_NOT_AVAILABLE' }
            New-Item -ItemType Directory -Path $StartupDir -Force | Out-Null
            $CmdText = "@echo off`r`nstart `"`" powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$Launcher`" -NoBrowser`r`n"
            [IO.File]::WriteAllText($StartupFallback,$CmdText,[Text.Encoding]::ASCII)
            if(-not (Test-Path -LiteralPath $StartupFallback -PathType Leaf)) { throw 'AUTOSTART_FALLBACK_WRITE_FAILED' }
            $CreatedStartupFallback = $true
            $Autostart = 'PASS'
            $AutostartMethod = 'STARTUP_FOLDER'
            Say 'AUTOSTART_FALLBACK' 'PASS_VERIFIED' 'Green'
        }
    }

    # 10. Start promoted build and re-run integration against the installed files.
    & $Launcher -NoBrowser
    $LiveHealth = Wait-Health 8820 20
    if(-not $LiveHealth) { throw 'FINAL_ENGINE_HEALTH_FAILED' }
    Say 'FINAL_ENGINE_HEALTH' 'PASS' 'Green'

    $FinalIntegrationLog = Join-Path $Stage 'final-integration.json'
    $old = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
    & $Python (Join-Path $Target 'integration_test.py') --base 'http://127.0.0.1:8820' --core-root $Core --require-core 2>&1 | Tee-Object -FilePath $FinalIntegrationLog
    $FinalIntegrationExit = $LASTEXITCODE
    $ErrorActionPreference = $old
    if($FinalIntegrationExit -ne 0) { throw ("FINAL_INTEGRATION_FAILED_EXIT={0}" -f $FinalIntegrationExit) }
    $FinalIntegration = Get-Content -LiteralPath $FinalIntegrationLog -Raw | ConvertFrom-Json
    if(-not $FinalIntegration.ok) { throw 'FINAL_INTEGRATION_RESULT_FAILED' }
    Say 'FINAL_INTEGRATION' ("PASS {0}/{1}" -f $FinalIntegration.passed,$FinalIntegration.total) 'Green'

    # 11. Add default recurring jobs once, if they are not already present.
    try {
        $status = Invoke-RestMethod -Uri 'http://127.0.0.1:8820/api/status' -TimeoutSec 8
        $names = @($status.schedules | ForEach-Object { [string]$_.name })
        if($names -notcontains 'Service health every 15 minutes') {
            $body = @{name='Service health every 15 minutes';kind='service_health';payload=@{recover=$true};schedule_type='interval';schedule_value='900';priority=25} | ConvertTo-Json -Depth 5
            Invoke-RestMethod -Uri 'http://127.0.0.1:8820/api/schedules' -Method Post -ContentType 'application/json' -Body $body -TimeoutSec 8 | Out-Null
        }
        if($names -notcontains 'Nightly incremental code index') {
            $body = @{name='Nightly incremental code index';kind='code_index';payload=@{root=$Core;max_files=5000};schedule_type='daily';schedule_value='02:00';priority=10} | ConvertTo-Json -Depth 5
            Invoke-RestMethod -Uri 'http://127.0.0.1:8820/api/schedules' -Method Post -ContentType 'application/json' -Body $body -TimeoutSec 8 | Out-Null
        }
        Say 'DEFAULT_SCHEDULES' 'PASS' 'Green'
    } catch { Say 'DEFAULT_SCHEDULES' ('WARN ' + $_.Exception.Message) 'Yellow' }

    # 12. Convenience shortcut only after the complete installed gate passes.
    try {
        $Desktop = [Environment]::GetFolderPath('Desktop')
        $UrlFile = Join-Path $Desktop 'Agape Work Engine.url'
        [IO.File]::WriteAllText($UrlFile,"[InternetShortcut]`r`nURL=http://127.0.0.1:8820/`r`n",[Text.UTF8Encoding]::new($false))
    } catch {}

    $Result = [ordered]@{
        build=$Build; overall='PASS'; installed=$true; core=$Core; install_path=$Target; data_root=$DataRoot;
        url='http://127.0.0.1:8820/'; payload_sha256=$PayloadHash; backup=$Backup;
        staged_selftests=("{0}/{1}" -f $Self.passed,$Self.total);
        staged_integration=("{0}/{1}" -f $Integration.passed,$Integration.total);
        final_integration=("{0}/{1}" -f $FinalIntegration.passed,$FinalIntegration.total);
        autostart=$Autostart; autostart_method=$AutostartMethod; core_service_gate='PASS';
        systems=@('durable-work-queue','checkpoints-retry','code-intelligence-context-pack','provider-circuits','fast-standard-deep-lanes','sweet-spot-optimizer','flight-recorder','scheduler-cron','lazy-plugin-registry','service-supervisor','resumable-chunk-uploads','content-addressed-store')
    }
    [IO.File]::WriteAllText($ResultPath,($Result|ConvertTo-Json -Depth 8),[Text.UTF8Encoding]::new($false))
    Write-Host ''
    Write-Host '================ CHATGPT_RESULT ================' -ForegroundColor Cyan
    $Result | ConvertTo-Json -Depth 8
    Write-Host '================================================'
    Say 'RESULT_FILE' $ResultPath 'Green'
    if(-not $NoOpen) { Start-Process 'http://127.0.0.1:8820/' }
}
catch {
    $ErrText = $_.Exception.Message
    try { if($CandidateProc -and -not $CandidateProc.HasExited) { Stop-Process -Id $CandidateProc.Id -Force -ErrorAction SilentlyContinue } } catch {}
    if($Cutover) {
        try { Stop-EngineOnPort 8820 } catch {}
        try { if(Test-Path $Target) { Remove-Item $Target -Recurse -Force } } catch {}
        if($OldTargetExisted -and (Test-Path (Join-Path $Backup 'agape-systems-engine'))) {
            try { Copy-Item (Join-Path $Backup 'agape-systems-engine') $Target -Recurse -Force; Say 'ROLLBACK_ENGINE' 'PASS' 'Yellow' } catch { Say 'ROLLBACK_ENGINE' 'FAIL' 'Red' }
        }
        if($OldLauncherExisted -and (Test-Path (Join-Path $Backup 'OPEN-AGAPE-WORK-ENGINE.ps1'))) {
            try { Copy-Item (Join-Path $Backup 'OPEN-AGAPE-WORK-ENGINE.ps1') $Launcher -Force } catch {}
        } elseif(Test-Path $Launcher) {
            try { Remove-Item $Launcher -Force } catch {}
        }
        if($CreatedStartupFallback -and (Test-Path $StartupFallback)) {
            try { Remove-Item $StartupFallback -Force } catch {}
        }
        if($OldStartupFallbackExisted -and (Test-Path (Join-Path $Backup 'Agape Work Engine.cmd'))) {
            try { Copy-Item (Join-Path $Backup 'Agape Work Engine.cmd') $StartupFallback -Force } catch {}
        }
    }
    $FailResult=[ordered]@{build=$Build;overall='FAIL';installed=$false;error=$ErrText;core=$Core;stage=$Stage;backup=$Backup;live_core_untouched=(-not $Cutover)}
    try { [IO.File]::WriteAllText($ResultPath,($FailResult|ConvertTo-Json -Depth 6),[Text.UTF8Encoding]::new($false)) } catch {}
    Write-Host ''
    Write-Host '================ CHATGPT_RESULT ================' -ForegroundColor Red
    $FailResult | ConvertTo-Json -Depth 6
    Write-Host '================================================'
    throw
}
